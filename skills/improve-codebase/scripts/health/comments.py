import hashlib
import re
import textwrap
from collections import Counter

KEPT_CLASSES = ("directive", "legal")
DIRECTIVE = re.compile(r"^///\s*<reference|^//go:|^//line |^#\s*syntax=|^/\*!")
TOOL_DIRECTIVE = re.compile(
    r"(?:^|#)[ \t]*(?:noqa|type:\s*ignore|pyright:|pragma:\s*no cover"
    r"|fmt:\s*(?:off|on|skip)|eslint-(?:disable|enable|env)"
    r"|@ts-(?:expect-error|ignore|nocheck|check)|prettier-ignore"
    r"|stylelint-(?:disable|enable)|istanbul ignore|c8 ignore"
    r"|webpack[A-Z]\w*\s*:|@jest-environment|@vitest-environment|@vite-ignore"
    r"|@refresh|ReSharper disable|<auto-generated|pylint:|mypy:|isort:|ruff:"
    r"|nosec|nolint)",
    re.M,
)
ENCODING = re.compile(r"^#.*coding[:=]\s*[-\w.]+")
LEGAL = re.compile(r"copyright|SPDX|^\W*(?:the\s+)?licen[sc]e", re.I)
MARKER = re.compile(r"\b(?:TODO|FIXME|HACK|XXX)\b")
BANNER = re.compile(r"([=\-#*~_])\1{3,}")
BRACKETS = re.compile(r"[\s{}()\[\];,]*")
LINE_COMMENT = re.compile(rb"///|//|#")
LINE_GAP = re.compile(rb"\r?\n[ \t]*")
CODE_SIGNAL = re.compile(
    r"[;{}]\s*$|\w\s*=\s*[^=\s]|\w\(|=>"
    r"|^\s*(?:def|class|import|from|return|raise|yield|await|async|if|elif|else"
    r"|for|while|try|except|finally|with|const|let|var|function|public|private"
    r"|protected|static|using|namespace|print|console\.|self\.)\b",
    re.M,
)
HTML_TAG = re.compile(r"<\/?[a-zA-Z][\w-]*(?:\s[^>]*)?\/?>")
CSS_CODE = re.compile(r"[\w-]+\s*:\s*[^;]+;|[^{]+\{[^}]*\}")
LOCATION_LIMIT = 50


def line_prefix(data, record):
    match = LINE_COMMENT.match(data, record["start"])
    return match[0] if match else None


def standalone(data, record):
    line_start = data.rfind(b"\n", 0, record["start"]) + 1
    return not data[line_start : record["start"]].strip()


def is_directive(text, line):
    return bool(
        (text.startswith("#!") and line == 1)
        or DIRECTIVE.search(text)
        or TOOL_DIRECTIVE.search(body_text(text))
        or (ENCODING.match(text) and line <= 2)
    )


def body_text(text):
    if text.startswith("/*"):
        inner = text[2:-2] if text.endswith("*/") else text[2:]
        lines = [re.sub(r"^\s*\*?\s?", "", row) for row in inner.splitlines()]
        return "\n".join(lines).strip()
    if text.startswith("<!--"):
        return text[4:-3].strip() if text.endswith("-->") else text[4:].strip()
    return "\n".join(
        re.sub(r"^[ \t]*(?:///|//|#)[ ]?", "", row) for row in text.splitlines()
    )


def looks_like_code(body, language, parse_with):
    if not body.strip() or not CODE_SIGNAL.search(body):
        return False
    if language == "html":
        return bool(HTML_TAG.search(body))
    if language in {"css", "scss"}:
        return bool(CSS_CODE.search(body))
    parser = parse_with(language)
    if parser is None:
        return False
    code = textwrap.dedent(body)
    if language == "python" and code.rstrip().endswith(":"):
        code += "\n    pass"
    elif language != "python" and code.rstrip().endswith("{"):
        code += "\n}"
    tree = parser.parse(code.encode("utf-8"))
    return tree is not None and not tree.root_node.has_error


def doc_comment(text, prefix, declaration):
    return declaration and (
        (text.startswith("/**") and not text.startswith("/**/")) or prefix == b"///"
    )


def classify(text, record, prefix, parse_with):
    if record["docstring"] or doc_comment(text, prefix, record["declaration"]):
        return "doc"
    body = body_text(text)
    if MARKER.search(body):
        return "marker"
    if BRACKETS.fullmatch(body.strip()) and body.strip():
        return "commented-code"
    letters = sum(c.isalnum() for c in body)
    visible = sum(not c.isspace() for c in body)
    if BANNER.search(body) or letters * 3 < visible or not visible:
        return "banner"
    if looks_like_code(body, record["language"], parse_with):
        return "commented-code"
    return "note"


def group_records(data, ordered, directive_flags):
    groups = []
    for record, directive in zip(ordered, directive_flags, strict=True):
        prefix = None if directive or record["docstring"] else line_prefix(data, record)
        current = record | {
            "prefix": prefix,
            "standalone": standalone(data, record),
            "records": [record],
            "kept": directive,
        }
        previous = groups[-1] if groups else None
        if (
            previous
            and prefix
            and not previous["kept"]
            and previous["prefix"] == prefix
            and previous["standalone"]
            and current["standalone"]
            and LINE_GAP.fullmatch(data[previous["end"] : record["start"]])
        ):
            previous["end"] = record["end"]
            previous["records"].append(record)
        else:
            groups.append(current)
    return groups


def mark_leading_legal(data, groups, texts, directives):
    cursor, legal, previous_legal_end = 0, set(), None
    for index, group in enumerate(groups):
        gap = data[cursor : group["start"]]
        if gap.strip(b" \t\r\n\xef\xbb\xbf"):
            break
        text = texts[index]
        adjacent = (
            previous_legal_end is not None
            and data[previous_legal_end : group["start"]].count(b"\n") <= 1
        )
        if (
            index not in directives
            and not group["docstring"]
            and (LEGAL.search(text) or adjacent)
        ):
            legal.add(index)
            previous_legal_end = group["end"]
        else:
            previous_legal_end = None
        cursor = group["end"]
    return legal


def classified_runs(data, group, parse_with):
    runs = []
    for record in group["records"]:
        text = data[record["start"] : record["end"]].decode("utf-8", "replace")
        label = classify(text, record, group["prefix"], parse_with)
        if runs and runs[-1][0] == label:
            runs[-1][2] = record
        else:
            runs.append([label, record, record])
    for label, first, last in runs:
        if label == "note" and first is not last:
            text = data[first["start"] : last["end"]].decode("utf-8", "replace")
            if looks_like_code(body_text(text), first["language"], parse_with):
                label = "commented-code"
        yield label, first["start"], last["end"]


def finalize_comments(source, data, records, parse_with):
    ordered = sorted(records, key=lambda record: record["start"])
    directive_flags = [
        not record["docstring"]
        and is_directive(
            data[record["start"] : record["end"]].decode("utf-8", "replace"),
            source.location(record["start"], record["end"])["line"],
        )
        for record in ordered
    ]
    groups = group_records(data, ordered, directive_flags)
    texts = [
        data[group["start"] : group["end"]].decode("utf-8", "replace")
        for group in groups
    ]
    directives = {index for index, group in enumerate(groups) if group["kept"]}
    legal = mark_leading_legal(data, groups, texts, directives)
    rows = []
    for index, group in enumerate(groups):
        if index in directives or index in legal:
            spans = [
                (
                    "directive" if index in directives else "legal",
                    group["start"],
                    group["end"],
                )
            ]
        else:
            spans = classified_runs(data, group, parse_with)
        for label, start, end in spans:
            location = source.location(start, end)
            rows.append(
                [
                    location["line"],
                    label,
                    location["end_line"] - location["line"] + 1,
                    hashlib.sha256(data[start:end].strip()).hexdigest()[:16],
                ]
            )
    return rows


def comment_evidence(rows):
    removable = [row for row in rows if row[1] not in KEPT_CLASSES]
    locations = []
    for line, label, lines, _ in removable[:LOCATION_LIMIT]:
        entry = {"line": line, "class": label}
        if lines > 1:
            entry["lines"] = lines
        locations.append(entry)
    return {
        "removable": len(removable),
        "by_class": dict(sorted(Counter(row[1] for row in removable).items())),
        "kept": dict(
            sorted(Counter(row[1] for row in rows if row[1] in KEPT_CLASSES).items())
        ),
        "locations": locations,
    }


def comment_signature(rows):
    return sorted([row[1], row[3]] for row in rows if row[1] not in KEPT_CLASSES)
