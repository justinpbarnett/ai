def digest(value):
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, ensure_ascii=True, allow_nan=False).encode()
    ).hexdigest()


def content_hash(data):
    return hashlib.sha256(data).hexdigest()


def git(root, *args, allowed=(0,), env=None):
    environment = dict(os.environ if env is None else env)
    for key in (
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_COMMON_DIR",
        "GIT_PREFIX",
    ):
        environment.pop(key, None)
    environment["GIT_OPTIONAL_LOCKS"] = "0"
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        env=environment,
        timeout=45,
    )
    if result.returncode not in allowed:
        raise OSError(f"git {args[0]} failed: {os.fsdecode(result.stderr).strip()}")
    return result


def discover_root(argument):
    path = Path(argument).expanduser().resolve(strict=True)
    if not path.is_dir():
        raise ValueError("root must be a directory")
    try:
        result = git(path, "rev-parse", "--show-toplevel", allowed=(0, 128))
    except FileNotFoundError:
        if any((parent / ".git").exists() for parent in (path, *path.parents)):
            raise ValueError(
                "Git is required to inventory this checkout safely"
            ) from None
        return path, False
    if not result.returncode:
        return Path(os.fsdecode(result.stdout.removesuffix(b"\n"))).resolve(), True
    if any((parent / ".git").exists() for parent in (path, *path.parents)):
        raise ValueError(
            "cannot discover Git worktree: " + os.fsdecode(result.stderr).strip()
        )
    return path, False


def normalize_scope(root, requested):
    paths = set()
    for item in requested or ["."]:
        path = Path(os.path.abspath(root / item))
        if not path.is_relative_to(root):
            raise ValueError(f"scope is outside root: {item!r}")
        if any(SECRET.search(part) for part in path.relative_to(root).parts):
            raise ValueError(f"scope crosses a protected path: {item!r}")
        if path.resolve() != path:
            raise ValueError(f"scope crosses a symlink: {item!r}")
        paths.add(path.relative_to(root).as_posix())
    return [p for p in sorted(paths) if not any(q != p and within(p, q) for q in paths)]


def within(path, prefix):
    return prefix == "." or path == prefix or path.startswith(prefix + "/")


def excluded(path, state_relative):
    parts = Path(path).parts
    name = parts[-1]
    if any(SECRET.search(part) for part in parts) or path.startswith(".config/gcloud/"):
        return "protected path"
    if any(part in ARTIFACTS for part in parts) or (
        state_relative and within(path, state_relative)
    ):
        return "runtime or VCS artifact"
    if any(part in DEPENDENCIES for part in parts) or any(
        parts[i : i + 2] == ("vendor", "bundle") for i in range(len(parts) - 1)
    ):
        return "installed dependencies"
    if within(path, ".pi/goals"):
        return "host goal runtime state"
    if name.lower() == "changelog.md":
        return "historical changelog"
    if name in LOCKFILES:
        return "dependency lockfile"
    if name.lower() in {".gitmodules", ".gitattributes"}:
        return "VCS configuration"
    if (
        name == "project.assets.json"
        and "obj" in parts
        or name.endswith(".nuget.dgspec.json")
    ):
        return "generated MSBuild output"
    if path.lower().endswith(
        (
            ".g.cs",
            ".g.i.cs",
            ".generated.cs",
            ".designer.cs",
            ".min.js",
            ".min.css",
            ".map",
            ".pb.go",
            ".pb.cc",
            ".pb.h",
        )
    ):
        return "generated filename"
    if Path(name).suffix.lower().lstrip(".") in NON_SOURCE:
        return "known non-source file type"
    return None


def git_files(root):
    staged = git(root, "ls-files", "--stage", "-z").stdout.split(b"\0")
    paths = {}
    for record in filter(None, staged):
        details, path = record.split(b"\t", 1)
        mode, _, stage = details.split()
        paths[os.fsdecode(path)] = (
            "submodule boundary"
            if mode == b"160000"
            else "unmerged index entry"
            if stage != b"0"
            else None
        )
    for raw in git(
        root, "ls-files", "--others", "--exclude-standard", "-z"
    ).stdout.split(b"\0"):
        if raw:
            name = os.fsdecode(raw)
            paths.setdefault(
                name.rstrip("/"), "nested Git boundary" if name.endswith("/") else None
            )
    return paths


def walk_files(root, state_relative):
    paths = {}

    def on_error(error):
        paths[Path(error.filename).relative_to(root).as_posix()] = (
            "directory cannot be enumerated"
        )

    for directory, folders, files in os.walk(root, onerror=on_error, followlinks=False):
        parent = Path(directory)
        for name in sorted(folders):
            path = parent / name
            relative = path.relative_to(root).as_posix()
            reason = excluded(relative, state_relative)
            if not reason:
                if path.is_symlink():
                    reason = "symlink not followed"
                elif (path / ".git").exists():
                    reason = "nested Git boundary"
                elif len(path.relative_to(root).parts) >= 64:
                    reason = "filesystem traversal depth exceeded"
            if reason:
                paths[relative] = reason
                folders.remove(name)
        for name in files:
            paths[(parent / name).relative_to(root).as_posix()] = None
    return paths


def safe_file(root, relative):
    path = root / relative
    if (
        Path(relative).is_absolute()
        or ".." in Path(relative).parts
        or not path.is_relative_to(root)
    ):
        raise ValueError(f"not a root-relative path: {relative!r}")
    if path.resolve() != path:
        raise ValueError(f"symlink not followed: {relative!r}")
    return path


def read_source(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as stream:
        st = os.fstat(stream.fileno())
        if not stat.S_ISREG(st.st_mode):
            raise ValueError("not a regular file")
        # Check the size again after reading in case a writer appended concurrently.
        if st.st_size > MAX_SOURCE_BYTES:
            raise ValueError("source exceeds size limit")
        data = stream.read(MAX_SOURCE_BYTES + 1)
    if len(data) > MAX_SOURCE_BYTES:
        raise ValueError("source exceeds size limit")
    return data


def source_language(path):
    suffix = Path(path).suffix.lower()
    if suffix in LANGUAGES:
        return LANGUAGES[suffix]
    if suffix.lstrip(".") in GENERIC or CONFIG.fullmatch(Path(path).name):
        return "generic"
    return None


def is_project_guide(path):
    name = Path(path)
    return (
        name.suffix.lower() in DOCUMENT_EXTENSIONS | {""}
        and name.stem.lower() in PROJECT_GUIDES
    )


def skipped_entry(reason, selected, *, incomplete=False):
    return (
        {"disposition": "incomplete" if incomplete else "excluded", "reason": reason}
        if selected
        else None
    )


def classify_content(name, data, hashed, selected):
    language = source_language(name)
    guide = is_project_guide(name)
    suffix = Path(name).suffix
    try:
        text = data.decode("utf-8-sig")
        if "\x00" in text or any(ord(c) < 9 for c in text[:8192]):
            raise UnicodeError("binary content")
    except UnicodeError:
        return skipped_entry(
            "binary or unsupported encoding",
            selected or guide,
            incomplete=bool(language or guide),
        )
    if GENERATED.search(b"\n".join(data.splitlines()[:12])):
        return skipped_entry("generated source header", selected)
    shebang = data.startswith(b"#!")
    if (
        not language
        and not shebang
        and (suffix.lower() in DOCUMENT_EXTENSIONS or guide)
    ):
        return {
            "disposition": "reference",
            "reason": "documentation; review context only",
            "hash": hashed,
        }
    if not language and (shebang or not suffix):
        language = "generic"
    return {
        "disposition": "source" if selected else "context",
        "hash": hashed,
        "language": language or "unknown",
        "bytes": len(data),
        "loc": sum(bool(line.strip()) for line in text.splitlines()),
    }


def inventory_entry(root, name, reason, selected):
    filename = Path(name).name
    config = (
        CONFIG.fullmatch(filename)
        or PROJECT.fullmatch(filename)
        or filename in LOCKFILES
    )
    if reason and not (config and reason == "dependency lockfile"):
        incomplete = reason in {
            "unmerged index entry",
            "directory cannot be enumerated",
            "filesystem traversal depth exceeded",
        }
        return skipped_entry(reason, selected, incomplete=incomplete), None, None
    try:
        path = safe_file(root, name)
        # Git can list tracked children under a directory replaced by a nested checkout.
        if any(
            (p / ".git").exists()
            for p in path.parents
            if p != root and p.is_relative_to(root)
        ):
            return skipped_entry("nested Git boundary", selected), None, None
        data = read_source(path)
    except FileNotFoundError:
        return skipped_entry("tracked path absent in worktree", selected), None, None
    except (OSError, ValueError, RuntimeError) as exc:
        detail = str(exc) if isinstance(exc, ValueError) else type(exc).__name__
        return (
            skipped_entry(
                detail,
                selected or config or is_project_guide(name),
                incomplete=not detail.startswith("symlink not followed"),
            ),
            None,
            None,
        )
    hashed = content_hash(data)
    entry = (
        skipped_entry(reason, selected)
        if reason
        else classify_content(name, data, hashed, selected)
    )
    return entry, data, hashed if config else None


def owning_project(name, projects):
    parent = Path(name).parent
    return next(
        (
            path.as_posix()
            for path in (parent, *parent.parents)
            if path.as_posix() in projects
        ),
        ".",
    )


def collect_entries(root, paths, scopes, state_relative, *, gather):
    projects = {
        Path(p).parent.as_posix()
        for p, reason in paths.items()
        if not reason
        and not excluded(p, state_relative)
        and PROJECT.fullmatch(Path(p).name)
    }
    entries, sources, rules = {}, {}, {}
    for name, boundary in sorted(paths.items()):
        selected = any(within(name, prefix) for prefix in scopes)
        entry, data, rule_hash = inventory_entry(
            root, name, boundary or excluded(name, state_relative), selected
        )
        if rule_hash is not None:
            rules[name] = rule_hash
        if entry is None:
            continue
        entries[name] = entry
        disposition = entry["disposition"]
        if disposition in {"source", "context", "reference"}:
            entry["project"] = owning_project(name, projects)
        if gather and disposition in {"source", "context"}:
            sources[name] = data
    return entries, sources, rules


def inventory(root, is_git, scopes, state_dir, *, gather=False):
    state_relative = (
        state_dir.relative_to(root).as_posix()
        if state_dir.is_relative_to(root)
        else None
    )
    paths = git_files(root) if is_git else walk_files(root, state_relative)
    entries, sources, rules = collect_entries(
        root, paths, scopes, state_relative, gather=gather
    )
    for scope in scopes:
        if scope != "." and not (root / scope).exists():
            entries[scope] = {
                "disposition": "incomplete",
                "reason": "requested scope does not exist",
            }
    observed = {
        path: entry
        for path, entry in entries.items()
        if entry["disposition"] != "excluded"
    }
    scoped = {
        path: entry
        for path, entry in observed.items()
        if entry["disposition"] == "incomplete"
        or any(within(path, prefix) for prefix in scopes)
    }
    return {
        "entries": entries,
        "rules": rules,
        "fingerprint": digest([scopes, observed, rules]),
        "scope_fingerprint": digest([scopes, scoped, rules]),
    }, sources


def hotspots(root, is_git, files):
    if not is_git:
        return {"available": False, "reason": "non-Git project"}
    try:
        result = git(
            root,
            "log",
            "-n",
            "100",
            "--format=",
            "--name-only",
            "-z",
            "--no-renames",
            "--diff-filter=ACMRT",
            "HEAD",
            allowed=(0, 128),
        )
    except (OSError, subprocess.TimeoutExpired):
        return {"available": False, "reason": "Git history unavailable"}
    if result.returncode:
        return {"available": False, "reason": "no readable HEAD"}
    counts = Counter(
        os.fsdecode(raw)
        for raw in result.stdout.split(b"\0")
        if os.fsdecode(raw) in files
    )
    return {"available": True, "recent_touches": dict(counts.most_common(100))}


HISTORY_COMMITS = 500
HISTORY_MAX_FILES = 30
COMMIT_MARK = b"\x01"


def status_commits(raw):
    tokens, commits, index = raw.split(b"\0"), [], 0
    while index < len(tokens):
        token = tokens[index].lstrip(b"\n")
        index += 1
        if token.startswith(COMMIT_MARK):
            commits.append([])
        elif token:
            width = 2 if token[:1] in b"RC" else 1
            paths = [os.fsdecode(t) for t in tokens[index : index + width]]
            commits[-1].append((os.fsdecode(token[:1]), *paths))
            index += width
    return commits


def working_tree_renames(root):
    result = git(root, "diff", "-M", "--name-status", "-z", "HEAD", allowed=(0, 128))
    if result.returncode:
        return {}
    entries = status_commits(COMMIT_MARK + b"\0" + result.stdout)[0]
    return {entry[1]: entry[2] for entry in entries if entry[0] == "R"}


def commit_history(root, is_git):
    if not is_git:
        return {"available": False, "reason": "non-Git project"}
    try:
        result = git(
            root,
            "log",
            "-n",
            str(HISTORY_COMMITS),
            "--format=%x01%H",
            "--name-status",
            "-z",
            "-M",
            "--diff-filter=ACMRT",
            "HEAD",
            allowed=(0, 128),
        )
        forward = working_tree_renames(root) if not result.returncode else {}
    except (OSError, subprocess.TimeoutExpired):
        return {"available": False, "reason": "Git history unavailable"}
    if result.returncode:
        return {"available": False, "reason": "no readable HEAD"}
    commits, remapped = [], set()
    for entries in status_commits(result.stdout):
        if len(entries) <= HISTORY_MAX_FILES:
            files = []
            for entry in entries:
                path = entry[-1]
                files.append(forward.get(path, path))
                if forward.get(path, path) != path:
                    remapped.add(path)
            commits.append(files)
        for entry in entries:
            if entry[0] == "R":
                forward[entry[1]] = forward.get(entry[2], entry[2])
    return {
        "available": True,
        "commits": commits,
        "window_commits": HISTORY_COMMITS,
        "max_commit_files": HISTORY_MAX_FILES,
        "mapped_paths": len(remapped),
    }
